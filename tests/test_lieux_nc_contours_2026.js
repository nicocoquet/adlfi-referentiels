/* Nouvelle-Calédonie : intégrité des 32 contours, séparation Pactols/COG, Dumbéa exclue. */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const ROOT=path.resolve(__dirname,'..');
const validate=require('../docs/assets/lieux-nc-contours.js');
const indexer=require('../docs/assets/lieux-outremer-search.js');
const raw=JSON.parse(fs.readFileSync(path.join(ROOT,'docs/data/lieux-outremer/recherche-2026.json'),'utf8'));
const index=new Map(indexer.creerIndex(raw).map(x=>[x.id,x]));
const fc=JSON.parse(fs.readFileSync(path.join(ROOT,'docs/data/lieux-outremer/contours-communes-nc-2026.geojson'),'utf8'));
const features=validate.verifier(fc,index);
assert.equal(features.length,32);
assert.ok(features.every(f=>f.properties.code.startsWith('988')&&f.properties.code!=='98805'));
assert.ok(features.every(f=>f.properties.ref_cog==='COMER:COM:'+f.properties.code));
assert.ok(features.every(f=>f.properties.ark_pactols===null));
assert.ok(features.every(f=>f.properties.limite_juridique_homologuee===false));
assert.equal(fc.provenance.restitutions_historiques,0);
assert.equal(fc.provenance.limites_juridiques_homologuees,false);
assert.throws(()=>validate.verifier({...fc,features:[...features,features[0]]},index),/non conforme/);
const mutation=JSON.parse(JSON.stringify(fc));
mutation.features[0].properties.code='98805';
assert.throws(()=>validate.verifier(mutation,index),/non conforme/);
const historical=JSON.parse(JSON.stringify(fc));
historical.provenance.cog_ref='1975-01-01';
assert.throws(()=>validate.verifier(historical,index),/non conforme/);
const map=fs.readFileSync(path.join(ROOT,'docs/assets/lieux-multiechelon.js'),'utf8');
assert.ok(map.includes("nc2026Features"));
assert.ok(map.includes("'nouvelle-caledonie:'"));
assert.ok(map.includes("['drom','spm','nouvelle-caledonie']"));
console.log('NC_32_INDEX_OK — 32 contours, Dumbéa exclue, 0 nouvel ARK ou contour historique');
