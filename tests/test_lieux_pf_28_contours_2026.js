'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const ROOT=path.resolve(__dirname,'..');
const api=require('../docs/assets/lieux-pf-contours.js');
const indexer=require('../docs/assets/lieux-outremer-search.js');
const indexSource=JSON.parse(fs.readFileSync(path.join(ROOT,'docs/data/lieux-outremer/recherche-2026.json'),'utf8'));
const index=new Map(indexer.creerIndex(indexSource).map(x=>[x.id,x]));
const fc=JSON.parse(fs.readFileSync(path.join(ROOT,'docs/data/lieux-outremer/contours-communes-pf-28-2026.geojson'),'utf8'));
const accepted=api.verifier(fc,index);
assert.equal(accepted.length,28);
assert.equal(fc.provenance.exclues_a_instruire.length,20);
assert.ok(fc.provenance.exclues_a_instruire.includes('98745'));
assert.ok(fc.provenance.exclues_a_instruire.includes('98726'));
assert.ok(accepted.every(f=>f.properties.code.startsWith('987')&&f.properties.code!=='98745'));
assert.ok(accepted.every(f=>f.properties.ref_cog==='COMER:COM:'+f.properties.code));
assert.ok(accepted.every(f=>f.properties.ark_pactols===null));
assert.ok(accepted.every(f=>f.properties.limite_juridique_homologuee===false));
assert.ok(accepted.some(f=>f.properties.code==='98735'));
assert.equal(fc.provenance.restitutions_historiques,0);
const hist=JSON.parse(JSON.stringify(fc));
hist.provenance.cog_ref='1975-01-01';
assert.throws(()=>api.verifier(hist,index),/non conforme/);
const dup=JSON.parse(JSON.stringify(fc));
dup.features[0].properties.code='98745';
assert.throws(()=>api.verifier(dup,index),/non conforme/);
const ark=JSON.parse(JSON.stringify(fc));
ark.features[0].properties.ark_pactols='26678/pcrtInventé';
assert.throws(()=>api.verifier(ark,index),/non conforme/);
const code=fs.readFileSync(path.join(ROOT,'docs/assets/lieux-multiechelon.js'),'utf8');
assert.ok(code.includes('pf2026Features'));
assert.ok(code.includes("'polynesie:'"));
assert.ok(code.includes("['drom','spm','nouvelle-caledonie','polynesie']"));
console.log('PF_28_INDEX_OK — 28 contours de référence, 20 exceptions, 0 nouvel ARK ou contour historique');
