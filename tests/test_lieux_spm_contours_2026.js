/* Saint-Pierre-et-Miquelon : deux contours 2026, fiches COMER et ARK existants. */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const ROOT=path.resolve(__dirname,'..');
const validate=require('../docs/assets/lieux-spm-contours.js');
const indexer=require('../docs/assets/lieux-outremer-search.js');
const raw=JSON.parse(fs.readFileSync(path.join(ROOT,'docs/data/lieux-outremer/recherche-2026.json'),'utf8'));
const index=new Map(indexer.creerIndex(raw).map(x=>[x.id,x]));
const fc=JSON.parse(fs.readFileSync(path.join(ROOT,'docs/data/lieux-outremer/contours-communes-spm-2026.geojson'),'utf8'));
const features=validate.verifier(fc,index);
assert.deepEqual(features.map(f=>f.properties.code),['97501','97502']);
assert.deepEqual(features.map(f=>f.properties.ref_cog),['COMER:COM:97501','COMER:COM:97502']);
assert.ok(features.every(f=>f.properties.ark_pactols===null));
assert.ok(features.every(f=>f.properties.limite_juridique_homologuee===false));
assert.equal(fc.provenance.restitutions_historiques,0);
assert.equal(fc.provenance.limites_juridiques_homologuees,false);
assert.equal(index.get('COMER:COM:97501').arkValide,'26678/pcrtQAMzeGHldU');
assert.equal(index.get('COMER:COM:97502').arkValide,'26678/pcrtYQmFfwxLq8');
assert.throws(()=>validate.verifier({...fc,provenance:{...fc.provenance,cog_ref:'1975-01-01'}},index),/non conforme/);
assert.throws(()=>validate.verifier({...fc,features:[...features,features[0]]},index),/non conforme/);
const copy=JSON.parse(JSON.stringify(fc));
copy.features[0].properties.ark_pactols='26678/pcrtInterdit';
assert.throws(()=>validate.verifier(copy,index),/non conforme/);
const other=JSON.parse(JSON.stringify(fc));
other.features[1].properties.ref_cog='DROM:COM:97502';
assert.throws(()=>validate.verifier(other,index),/non conforme/);
const dup=JSON.parse(JSON.stringify(fc));
dup.features[1].properties.code='97501';
assert.throws(()=>validate.verifier(dup,index),/non conforme/);
const script=fs.readFileSync(path.join(ROOT,'docs/assets/lieux-multiechelon.js'),'utf8');
assert.ok(script.includes("p.zone+':'+p.code"));
assert.ok(script.includes("spm2026Features"));
assert.ok(script.includes("x.code?.startsWith('975')?'spm:'"));
console.log('SPM_2_INDEX_OK — COMER 97501 et 97502, deux contours, 0 nouvel ARK et 0 limite historique');
